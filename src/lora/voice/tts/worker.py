@dataclass(frozen=True)
class TtsJob:
    """Work unit sent to the TTS worker process."""

    job_id: str
    text: str
    voice: str = DEFAULT_KOKORO_VOICE


@dataclass(frozen=True)
class TtsAudioChunk:
    """Audio output generated by the TTS worker."""

    job_id: str
    text: str
    samples: np.ndarray
    sample_rate: int = 24000
    duration: float = 0.0
    is_last: bool = True
    error: str | None = None


def resolve_kokoro_voice(voice: str | None) -> str:
    """Resolve a requested voice name or legacy alias to a valid Kokoro voice ID."""
    v = (voice or DEFAULT_KOKORO_VOICE).strip().lower()
    if v in KOKORO_VOICES:
        return v
    if v in KOKORO_VOICE_ALIASES:
        return KOKORO_VOICE_ALIASES[v]
    return DEFAULT_KOKORO_VOICE



# ---------------------------------------------------------------------------
# Kokoro-ONNX CPU Backend (Primary TTS — 0 MB GPU VRAM)
# ---------------------------------------------------------------------------
_CACHED_KOKORO_MODEL: Any = None
_KOKORO_STATUS: dict[str, str] = {"state": "unloaded", "reason": "", "fix": "", "dir": ""}
_KOKORO_LOAD_LOCK = threading.Lock()
_KOKORO_SYNTH_LOCK = threading.Lock()
FIX_KOKORO = (
    r"run: python scripts\download_models.py --kokoro-only "
    r"(places kokoro-v1.0.onnx + voices-v1.0.bin in models\kokoro)"
)


def candidate_kokoro_dirs(models_dir: str = "models/kokoro") -> list[Path]:
    """Locate directories that may contain kokoro-v1.0.onnx and voices-v1.0.bin."""
    cands: list[Path] = []
    for env_key in ("LORA_KOKORO_DIR", "LORA_TTS_MODEL_DIR"):
        env_val = os.environ.get(env_key)
        if env_val:
            cands.append(Path(env_val))
    base = Path(models_dir)
    if base.is_file():
        cands.append(base.parent)
    else:
        cands.append(base)
        cands.append(base.parent / "kokoro")
    cands.extend([
        Path("models/kokoro"),
        Path("models/voice"),
        Path(r"C:\Models\kokoro"),
        Path(r"C:\Models"),
    ])
    out: list[Path] = []
    seen: set[str] = set()
    for c in cands:
        key = str(c).lower()
        if key not in seen:
            seen.add(key)
            out.append(c)
    return out


def find_kokoro_files(models_dir: str = "models/kokoro") -> tuple[Path, Path] | None:
    """Return (onnx_model_path, voices_bin_path) if present on disk."""
    for folder in candidate_kokoro_dirs(models_dir):
        if not folder.is_dir():
            continue
        onnx_candidates = [
            folder / "kokoro-v1.0.onnx",
            folder / "kokoro-v1.0.int8.onnx",
            folder / "kokoro-v0_19.onnx",
            *sorted(folder.glob("kokoro*.onnx")),
        ]
        voice_candidates = [
            folder / "voices-v1.0.bin",
            folder / "voices.bin",
            folder / "voices.npz",
            *sorted(folder.glob("voices*.bin")),
        ]
        onnx_file = next((p for p in onnx_candidates if p.is_file()), None)
        voice_file = next((p for p in voice_candidates if p.is_file()), None)
        if onnx_file and voice_file:
            return onnx_file, voice_file
    return None


def get_kokoro_model(models_dir: str = "models/kokoro") -> Any:
    """Load and cache the Kokoro-ONNX TTS model on CPU (0 MB GPU VRAM)."""
    global _CACHED_KOKORO_MODEL
    if _CACHED_KOKORO_MODEL is not None:
        return _CACHED_KOKORO_MODEL
    with _KOKORO_LOAD_LOCK:
        if _CACHED_KOKORO_MODEL is not None:
            return _CACHED_KOKORO_MODEL
        if _KOKORO_STATUS["state"] == "failed":
            return None
        try:
            from kokoro_onnx import Kokoro
        except Exception as exc:
            _KOKORO_STATUS.update({
                "state": "failed",
                "reason": f"kokoro-onnx is not installed ({exc})",
                "fix": FIX_KOKORO,
                "dir": "",
            })
            return None

        files = find_kokoro_files(models_dir)
        if files is None:
            _KOKORO_STATUS.update({
                "state": "failed",
                "reason": f"Kokoro model files (kokoro-v1.0.onnx, voices-v1.0.bin) not found in {models_dir}",
                "fix": FIX_KOKORO,
                "dir": str(models_dir),
            })
            return None

        onnx_path, voices_path = files
        try:
            logger.info("Loading Kokoro-ONNX TTS on CPU from %s ...", onnx_path.parent)
            import onnxruntime as ort

            options = ort.SessionOptions()
            options.intra_op_num_threads = 2
            options.inter_op_num_threads = 1
            session = ort.InferenceSession(
                str(onnx_path), sess_options=options, providers=["CPUExecutionProvider"]
            )
            model = Kokoro.from_session(session, str(voices_path))
            _CACHED_KOKORO_MODEL = model
            _KOKORO_STATUS.update({
                "state": "loaded",
                "reason": "",
                "fix": "",
                "dir": str(onnx_path.parent),
            })
            logger.info("Kokoro-ONNX TTS ready (default voice: %s, 0 MB GPU VRAM).", DEFAULT_KOKORO_VOICE)
            return model
        except Exception as exc:
            _KOKORO_STATUS.update({
                "state": "failed",
                "reason": f"Kokoro failed to load ({type(exc).__name__}: {exc})",
                "fix": FIX_KOKORO,
                "dir": str(onnx_path.parent),
            })
            logger.warning("Kokoro-ONNX load failed: %s", exc)
            return None


def _kokoro_generate(model: Any, text: str, voice: str = DEFAULT_KOKORO_VOICE) -> tuple[np.ndarray, int]:
    """Synthesize speech with Kokoro-ONNX under lock (protects non-reentrant espeak-ng C state)."""
    target_voice = resolve_kokoro_voice(voice)
    with _KOKORO_SYNTH_LOCK:
        try:
            available = list(model.get_voices()) if hasattr(model, "get_voices") else []
            if available and target_voice not in available:
                target_voice = DEFAULT_KOKORO_VOICE if DEFAULT_KOKORO_VOICE in available else available[0]
        except Exception:
            pass
        lang = "en-gb" if target_voice.startswith("b") else "en-us"
        samples, sr = model.create(text, voice=target_voice, speed=1.0, lang=lang)
    return np.asarray(samples, dtype=np.float32).reshape(-1), int(sr)

class KokoroTtsWorkerProcess:
    """Kokoro-only CPU speech. Missing voice files return an actionable error."""

    def __init__(self, models_dir: str = "models/kokoro", default_voice: str = DEFAULT_KOKORO_VOICE):
        self.models_dir = models_dir
        self.default_voice = resolve_kokoro_voice(default_voice)

    def preload(self) -> bool:
        return get_kokoro_model(self.models_dir) is not None

    def diagnosis(self) -> dict[str, Any]:
        ready = self.preload()
        return {
            "ok": ready, "backend": "kokoro", "device": "cpu",
            "summary": "Kokoro CPU voice ready." if ready else "Kokoro voice unavailable.",
            "detail": _KOKORO_STATUS["reason"],
            "fix": "" if ready else FIX_KOKORO,
        }

    def get_supported_voices(self) -> list[str]:
        return list(KOKORO_VOICES)

    def synthesize(self, text: str, job_id: str = "1", voice: str = "default") -> TtsAudioChunk:
        samples, rate, error = np.zeros(0, dtype=np.float32), 24000, None
        if text.strip():
            try:
                model = get_kokoro_model(self.models_dir)
                if model is None:
                    raise RuntimeError(f"{_KOKORO_STATUS['reason']}. {FIX_KOKORO}")
                target = self.default_voice if voice == "default" else resolve_kokoro_voice(voice)
                samples, rate = _kokoro_generate(model, text, target)
            except Exception as exc:
                error = f"Kokoro CPU speech failed: {exc}"
                logger.warning("%s", error)
        return TtsAudioChunk(job_id=job_id, text=text, samples=samples, sample_rate=rate,
                             duration=len(samples) / rate, error=error)

    def shutdown(self) -> None:
        """No external speech process or GPU allocation to release."""

    stop = shutdown


class Qwen3TtsWorkerProcess(KokoroTtsWorkerProcess):
    """Compatibility name for CPU Kokoro; the former Qwen backend is retired.

    Historical constructor arguments remain accepted. Process isolation is now
    owned by lora.voice.isolation.ProcessKokoro, as in the desktop application.
    """

    def __init__(self, models_dir="models/kokoro", tokenizer_dir=None,
                 default_voice=DEFAULT_KOKORO_VOICE, spawn_process=False, cpu_only=True):
        super().__init__(models_dir=models_dir, default_voice=default_voice)
        self.tokenizer_dir = tokenizer_dir
        self.spawn_process = False
        self.cpu_only = True

    def start(self):
        """Compatibility no-op; the application owns native process isolation."""


def tts_diagnosis(models_dir="models/kokoro"):
    """Compatibility helper reporting the supported CPU backend only."""
    return KokoroTtsWorkerProcess(models_dir).diagnosis()
